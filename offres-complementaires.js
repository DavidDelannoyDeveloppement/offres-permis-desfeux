(function () {
  const catalogue = window.DESFEUX_OFFRES_COMPLEMENTAIRES;

  const sections = [
    {
      id: 'offres-cpf-b',
      title: 'Permis B financés par CPF',
      offerIds: ['ELGEA-101', 'ELGEA-103', 'ELGEA-74', 'ELGEA-71', 'ELGEA-104']
    },
    {
      id: 'offre-code',
      title: 'Formation au code de la route',
      offerIds: ['ELGEA-99']
    },
    {
      id: 'offres-a1',
      title: 'Permis A1 — 125 cm³',
      offerIds: ['ELGEA-52', 'ELGEA-55']
    },
    {
      id: 'offres-cpf-moto-remorque',
      title: 'Offres moto et remorque complémentaires',
      offerIds: ['ELGEA-35', 'CPF-BE-SANS-CODE', 'CPF-BE-AVEC-CODE', 'CPF-A2-AVEC-CODE', 'CPF-A2-SANS-CODE']
    },
    {
      id: 'offres-retour-passerelle',
      title: 'Retour au permis et passerelle B vers A1',
      offerIds: ['ELGEA-100', 'ELGEA-24']
    }
  ];

  const pdfByOffer = {
    'ELGEA-24': 'PASSERELLE B VERS A1 (125 CC) 7 HEURES.pdf',
    'ELGEA-35': 'PERMIS BE sans CODE.pdf',
    'CPF-BE-SANS-CODE': 'PERMIS BE CPF.pdf',
    'CPF-BE-AVEC-CODE': 'PERMIS BE CPF.pdf'
  };

  function escapeHtml(value) {
    return String(value == null ? '' : value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  function money(value) {
    const amount = Number(value || 0);
    const decimals = Math.abs(amount - Math.round(amount)) > 0.001 ? 2 : 0;
    return amount.toLocaleString('fr-FR', {
      minimumFractionDigits: decimals,
      maximumFractionDigits: 2
    }) + ' €';
  }

  function pluralUnit(unit, quantity) {
    if (Number(quantity) <= 1) return unit;
    if (unit === 'heure') return 'heures';
    if (unit === 'unité') return 'unités';
    return unit;
  }

  function renderLine(line) {
    const quantity = Number(line.quantity || 0);
    const multiplier = quantity === 1
      ? ''
      : quantity.toLocaleString('fr-FR') + ' ' + escapeHtml(pluralUnit(line.unit, quantity)) + ' × ';
    const detail = line.detail ? ' — ' + escapeHtml(line.detail) : '';
    return '<li>' + escapeHtml(line.label) + detail + ' : ' + multiplier +
      '<span class="detail-price">' + money(line.unitPriceTtc) + '</span></li>';
  }

  function renderDocuments(offer) {
    const documents = [];
    if (pdfByOffer[offer.id]) documents.push({ label: 'Offre', file: pdfByOffer[offer.id] });
    if (offer.category !== 'Code') {
      documents.push(
        { label: 'Mandat majeur', file: 'MANDAT_MAJEUR.pdf' },
        { label: 'Mandat mineur', file: 'MANDAT_MINEUR.pdf' }
      );
    }
    documents.push({ label: 'Règlement intérieur', file: 'REGLEMENT_INTERIEUR.pdf' });

    const docsId = 'docs-' + offer.id.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    return '<div class="offer-card__actions">' +
      '<button type="button" class="btn btn--primary js-toggle-docs" aria-expanded="false" aria-controls="' + docsId + '">Imprimer les documents</button>' +
      '<div class="offer-docs" id="' + docsId + '">' + documents.map(function (document) {
        return '<button type="button" class="offer-docs__item js-print-pdf" data-pdf="' + escapeHtml(document.file) + '">' + escapeHtml(document.label) + '</button>';
      }).join('') + '</div></div>';
  }

  function renderOffer(offer, index) {
    const offerLines = catalogue.lines
      .filter(function (line) { return line.offerId === offer.id; })
      .sort(function (a, b) { return a.order - b.order; });
    const badges = [
      offer.financing === 'CPF' ? '<span class="offer-card__badge">CPF</span>' : '',
      offer.transmission !== 'Sans objet' ? '<span class="offer-card__badge offer-card__badge--soft">' + escapeHtml(offer.transmission) + '</span>' : ''
    ].join('');

    return '<article class="offer-card' + (index === 0 ? ' offer-card--featured' : '') + '">' +
      (badges ? '<div class="offer-card__meta">' + badges + '</div>' : '') +
      '<h3>' + escapeHtml(offer.title) + '</h3>' +
      '<p class="offer-card__price">' + money(offer.totalTtc) + '</p>' +
      '<ul class="offer-card__list">' + offerLines.map(renderLine).join('') + '</ul>' +
      renderDocuments(offer) + '</article>';
  }

  function renderSection(section) {
    const offers = section.offerIds.map(function (id) {
      return catalogue.offers.find(function (offer) { return offer.id === id; });
    }).filter(Boolean);
    const contentId = 'content-' + section.id;
    return '<section class="permit-section" id="' + section.id + '">' +
      '<button type="button" class="permit-toggle" aria-expanded="false" aria-controls="' + contentId + '">' +
      '<span class="permit-toggle__title">' + escapeHtml(section.title) + '</span>' +
      '<span class="permit-toggle__icon">+</span></button>' +
      '<div class="permit-content" id="' + contentId + '"><div class="offers-grid">' +
      offers.map(renderOffer).join('') + '</div></div></section>';
  }

  document.addEventListener('DOMContentLoaded', function () {
    const root = document.getElementById('additional-offers-root');
    if (!root || !catalogue) return;
    root.innerHTML = sections.map(renderSection).join('');
  });
})();
